@app.route('/api/predict')
def api_predict():
    month_val = request.args.get('month', '')
    if not month_val:
        return jsonify({"error": "Bulan tidak valid"}), 400
    
    try:
        dt = datetime.datetime.strptime(month_val, "%Y-%m")
        # Target is the end of the requested month
        target_date = dt + relativedelta(months=1) - relativedelta(days=1)
        month_name = months_id[dt.month-1]
        formatted_month = f"{month_name} {dt.year}"
    except ValueError:
        return jsonify({"error": "Format bulan salah"}), 400

    if target_date <= ts.index[-1]:
        return jsonify({
            "month": formatted_month,
            "predicted": round(monthly_actual.iloc[-1]),
            "lower": round(monthly_actual.iloc[-1]) - 50,
            "upper": round(monthly_actual.iloc[-1]) + 50
        })

    forecast_df = forecast_future_internal(target_date)
    mask = (forecast_df.index.year == dt.year) & (forecast_df.index.month == dt.month)
    month_data = forecast_df[mask]
    
    if len(month_data) == 0:
         return jsonify({"error": "Gagal menghitung rentang"}), 400
         
    pred_mean = month_data['Price'].mean()
    std_mean = month_data['Std'].mean()
    
    margin = 1.96 * std_mean
    
    return jsonify({
        "month": formatted_month,
        "predicted": round(pred_mean),
        "lower": round(pred_mean - margin),
        "upper": round(pred_mean + margin)
    })

@app.route('/api/add_actual', methods=['POST'])
def add_actual():
    data = request.json
    month_val = data.get('month')
    price = data.get('price')
    
    if not month_val or not price:
        return jsonify({"error": "Data tidak lengkap"}), 400
        
    try:
        dt = datetime.datetime.strptime(month_val, "%Y-%m")
        # Inject data point on the 1st of the month so that forward-fill populates the whole month with this price.
        # This guarantees the monthly average calculation aligns with the injected price.
        inject_date = dt.replace(day=1).strftime("%Y-%m-%d")
        price = float(price)
    except Exception as e:
        return jsonify({"error": str(e)}), 400

    new_data = pd.DataFrame([{"Date_Param": inject_date, "Price": price}])
    new_data.to_csv(ADDITIONAL_DATA_PATH, mode='a', header=not os.path.exists(ADDITIONAL_DATA_PATH), index=False)
    
    # Reload model
    try:
        load_model_and_data()
    except Exception as e:
        return jsonify({"error": "Gagal memuat ulang data"}), 500
        
    return jsonify({"message": "Berhasil menyuntikkan data aktual baru. Model telah diperbarui!"})

